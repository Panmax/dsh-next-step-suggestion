/**
 * Zero-dependency bundler producing root `client.js` in DSH's `window.__ModuleLoader__.load` format
 * from `src/client-core.js` and `src/client-entry.js`.
 */

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const rootDir = resolve(dirname(fileURLToPath(import.meta.url)), '..')

function stripModuleSyntax(source) {
  return source
    .replace(/^\s*import\s+\{[\s\S]*?\}\s+from\s+['"][^'"]+['"]\s*;?\s*$/gmu, '')
    .replace(/^\s*export\s+(const|function|async\s+function)\s+/gmu, '$1 ')
    .trim()
}

export function generateClientBundle() {
  const coreSource = stripModuleSyntax(readFileSync(resolve(rootDir, 'src/client-core.js'), 'utf8'))
  const entrySource = stripModuleSyntax(readFileSync(resolve(rootDir, 'src/client-entry.js'), 'utf8'))

  return `/* Generated by scripts/build-client.mjs — do not edit directly. */
window.__ModuleLoader__.load({
  id: 'dsh-next-step-suggestion',
  factory(require) {
    const React = require('react');

${coreSource}

${entrySource}

    return createClientPlugin(React);
  },
});
`
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const outPath = resolve(rootDir, 'client.js')
  writeFileSync(outPath, generateClientBundle(), 'utf8')
  console.log(`Wrote ${outPath}`)
}
